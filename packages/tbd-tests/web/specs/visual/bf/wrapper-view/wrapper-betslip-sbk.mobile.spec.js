const MODULE_NAME = "wrapper";

describe("Wrapper View with betslip", () => {
  beforeAll(async () => {
    await mockService.mockHttpRequest(
      await getIndexHTML(BFF_MOCK.urn, {
        clientContext: {
          platform: "android",
          uiVariant: "mobile",
          wrapper: {
            wrapperName: "GamingWrapper",
            bridgeAPIVersion: "1.0.0",
          },
          webWrappedExperience: true,
        },
        BET_CONFIRMATION_STEP: { isActive: true },
      }),
    );
    await Promise.all([
      mockService.mockFonts(getMockFonts()),
      mockService.mockHttpRequest(getSportsLayout(BFF_MOCK)),
      mockService.mockHttpRequest(getMarketPrices(SMP_MOCK, { ignoreRequestedMarketIdsMatch: true })),
      mockService.mockHttpRequest(getImplyBetsResponse(SINGLE_MOCK)),
    ]);

    await browser.url(routes.getEventViewUrl(EVENT_TYPE_ID));
    await browser.waitUntilDisplayed(sportPagePO.actionLink[0]);

    await browser.waitUntilEquals(firstSbkRunnerPO.odd, "1.1");
    await firstSbkRunnerPO.sportsbookBetButton.click();

    await betslipDrawerPO.header.waitForClickable();
    await betslipDrawerPO.header.click();
    await browser.waitUntilImageEquals(`${MODULE_NAME}_[PRPI-1591]_wrapper_view_with_collapsed_betslip_displayed`);
  });

  it("[PRPI-1591]_wrapper_view_with_collapsed_betslip_displayed`)", async () => {
    expect(await browser.checkScreen(`${MODULE_NAME}_[PRPI-1591]_wrapper_view_with_collapsed_betslip_displayed`)).toBe(
      0,
    );
  });
});
